function tip(id) {
  if (!J.seenTips) J.seenTips = {};
  if (J.seenTips[id] || !TIPS[id]) return '';
  return '<div class="tipcard"><div class="hand">' + TIPS[id][0] + '</div><p>' + TIPS[id][1] + '</p><button class="btn ghost" data-a="tipOk" data-v="' + id + '">知道了</button></div>';
}
Object.assign(ACT, {
  tipOk(id) { if (!J.seenTips) J.seenTips = {}; J.seenTips[id] = true; saveJournal(); render(); },
  tipReset() { J.seenTips = {}; saveJournal(); render(); }
});
